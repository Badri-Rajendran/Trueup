"""Provider ports (S0 §3) — the only interfaces `app/services/` may depend on for outside-world
calls. Each `Protocol` gets a real adapter and a fake adapter, tested by the identical contract
suite (`tests/contract/`). Orchestrator-owned — escalate rather than editing directly.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum
from typing import TYPE_CHECKING, Protocol

if TYPE_CHECKING:
    import uuid
    from datetime import date, datetime

    from app.core.money import Money, Price, Units


# --- KycPort (S2 §4/§5.1, ADR 9 — Stripe Identity) --------------------------------------------


@dataclass(frozen=True, slots=True)
class KycSessionHandle:
    """What `KycPort.create_verification_session` hands back to start the hosted flow (S2 §6)."""

    provider_session_id: str
    client_secret: str


class KycPort(Protocol):
    """The verdict arrives as a webhook through `inbound_event` intake (S2 §4); this only starts a session."""

    def create_verification_session(self, *, customer_id: str) -> KycSessionHandle: ...

    def retrieve_verification_session(self, *, provider_session_id: str) -> str:
        """The provider's current raw status string for an existing session -- the safety net for
        when a verdict webhook hasn't arrived yet (or, in local dev, can't reach the app at all)."""
        ...


# --- BankPort (S2 §5.1, FR-4/41/42/43 — Plaid) ------------------------------------------------


@dataclass(frozen=True, slots=True)
class BankLinkHandle:
    """What `BankPort.exchange_public_token` hands back after linking (S2 §3.3/§5.1). `access_token`
    is plaintext exactly once, at exchange time — caller encrypts before it touches `bank_link`."""

    plaid_item_id: str
    access_token: str


@dataclass(frozen=True, slots=True)
class LinkTokenHandle:
    """What `BankPort.create_link_token` hands back to open Plaid Link client-side."""

    link_token: str
    expiration: datetime


class BankPort(Protocol):
    def create_link_token(self, *, client_user_id: str) -> LinkTokenHandle: ...

    def exchange_public_token(self, *, public_token: str) -> BankLinkHandle: ...


