# --- CustodianFilePort (S7 §3/§9 — the morning custodian file, simulated in v1) ---------------


class CustodianTransactionType(StrEnum):
    TRADE = "trade"
    DIVIDEND = "dividend"
    DEPOSIT = "deposit"
    WITHDRAWAL = "withdrawal"
    FEE = "fee"


@dataclass(frozen=True, slots=True)
class CustodianPositionRow:
    """`positions.csv` (S7 §3.1) — one row per `(customer_id, security_id)` held."""

    customer_id: uuid.UUID
    security_id: uuid.UUID
    quantity: Units
    as_of_date: date


@dataclass(frozen=True, slots=True)
class CustodianCashRow:
    """`cash.csv` (S7 §3.2) — the custodian's view of one customer's settled cash."""

    customer_id: uuid.UUID
    settled_cash: Money
    as_of_date: date


@dataclass(frozen=True, slots=True)
class CustodianTransactionRow:
    """`transactions.csv` (S7 §3.3) — one row per custodian-side transaction."""

    custodian_transaction_id: str
    customer_id: uuid.UUID | None
    security_id: uuid.UUID | None
    transaction_type: CustodianTransactionType
    amount_money: Money
    quantity: Units | None
    effective_date: date


@dataclass(frozen=True, slots=True)
class CustodianFileSet:
    """The three files one morning run delivers (S7 §3). `is_simulated` is FR-33's structural
    "clearly labelled" tag."""

    positions: list[CustodianPositionRow]
    cash: list[CustodianCashRow]
    transactions: list[CustodianTransactionRow]
    is_simulated: bool


class CustodianFilePort(Protocol):
    """The morning custodian file source (S7 §3). No real custodian feed is contracted yet (S7 §12)."""

    def fetch_files(self, *, market_date: date) -> CustodianFileSet: ...


# --- PaymentPort (S10 §5/§7, ADR 10 — Stripe Billing) -----------------------------------------


@dataclass(frozen=True, slots=True)
class PaymentMethodHandle:
    """What `PaymentPort.attach_payment_method` hands back (S10 §7): the mapped Stripe customer
    and the payment method now attached as default."""

    stripe_customer_id: str
    stripe_payment_method_id: str


@dataclass(frozen=True, slots=True)
class ChargeHandle:
    """What a successful `PaymentPort.charge` hands back. `status` is the provider's raw status
    string; interpreting it into `FeeChargeStatus` is `FeeChargeService`'s job, not the port's."""

    stripe_charge_id: str
    status: str


class PaymentDeclinedError(RuntimeError):
    """The provider synchronously refused the charge — distinct from a transport/config failure.
    `FeeChargeService`/`DunningService` catch this to start/continue dunning (S10 §5)."""

    def __init__(self, *, reason: str) -> None:
        super().__init__(f"payment declined: {reason}")
        self.reason = reason


class PaymentPort(Protocol):
    """Stripe Billing, never Alpaca cash (ADR 10). `charge()` is synchronous, off-session; an
    async webhook confirmation also arrives via `inbound_event` intake (S10 §7)."""

    def attach_payment_method(
        self, *, stripe_customer_id: str | None, customer_email: str, payment_method_id: str
    ) -> PaymentMethodHandle: ...

    def charge(
        self,
        *,
        stripe_customer_id: str,
        stripe_payment_method_id: str,
        amount: Money,
        idempotency_key: str,
    ) -> ChargeHandle:
        """Raises `PaymentDeclinedError` on decline. `idempotency_key` must be stable across
        retries (S10 §5: `fee_charge.id`) so a retried outbox call never double-charges."""
        ...
